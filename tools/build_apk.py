"""Build a debug-signed Android APK for Treasure Quest.

Uses only Android SDK command line tools (aapt2 / d8 / zipalign / apksigner),
no Gradle, no Android Studio required.

Usage:
    python tools/build_apk.py [--version-code 1] [--version-name 0.1.0] [--skip-icons]

Inputs:
    android/app/src/main/AndroidManifest.xml
    android/app/src/main/java/**/*.java
    android/app/src/main/res/**            (icons generated by tools/make_icons.py)
    web/**                                 (copied into assets/web as bundled content)
    web/version.json                       (bundled content version)

Output:
    dist/treasure-quest-<versionName>-debug.apk  (+ sha256 + apk-<ver>.json)
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANDROID_DIR = os.path.join(PROJECT_ROOT, "android")
MAIN_DIR = os.path.join(ANDROID_DIR, "app", "src", "main")
MANIFEST = os.path.join(MAIN_DIR, "AndroidManifest.xml")
JAVA_SRC = os.path.join(MAIN_DIR, "java")
RES_DIR = os.path.join(MAIN_DIR, "res")
ASSETS_DIR = os.path.join(MAIN_DIR, "assets")
# Allow bundling a different web snapshot (e.g. an older content version for OTA testing):
#   TQ_WEB_DIR=... python tools/build_apk.py
WEB_DIR = os.environ.get("TQ_WEB_DIR") or os.path.join(PROJECT_ROOT, "web")
DIST_DIR = os.path.join(PROJECT_ROOT, "dist")
WORK_DIR = os.path.join(ANDROID_DIR, "build", "manual")

SDK = os.environ.get("ANDROID_SDK_ROOT") or os.path.join(os.environ["LOCALAPPDATA"], "Android", "Sdk")
BUILD_TOOLS = os.path.join(SDK, "build-tools", "35.0.0")
ANDROID_JAR = os.path.join(SDK, "platforms", "android-35", "android.jar")
AAPT2 = os.path.join(BUILD_TOOLS, "aapt2.exe")
ZIPALIGN = os.path.join(BUILD_TOOLS, "zipalign.exe")
APKSIGNER_BAT = os.path.join(BUILD_TOOLS, "apksigner.bat")
D8_BAT = os.path.join(BUILD_TOOLS, "d8.bat")
DEBUG_KEYSTORE = os.path.join(PROJECT_ROOT, ".tooling", "debug.keystore")

REQUIRED_WEB = [
    "index.html",
    "version.json",
    "js/core/util.js",
    "js/core/audio.js",
    "js/core/input.js",
    "js/core/graphics.js",
    "js/core/level_data.js",
    "js/core/game.js",
    "js/shell/save.js",
    "js/shell/net.js",
    "js/shell/ui.js",
    "js/shell/boot.js",
]


def java_major_version(jdk):
    javac = os.path.join(jdk, "bin", "javac.exe")
    if not os.path.exists(javac):
        return 0
    try:
        r = subprocess.run([javac, "-version"], capture_output=True, text=True, timeout=30)
        out = ((r.stdout or "") + " " + (r.stderr or "")).strip()
        m = re.search(r"javac\s+(\d+)", out)
        return int(m.group(1)) if m else 0
    except Exception:  # noqa: BLE001
        return 0


def jdk_candidates():
    cands = []
    if os.environ.get("TQ_JDK"):
        cands.append(os.environ["TQ_JDK"])
    if os.environ.get("JAVA_HOME"):
        cands.append(os.environ["JAVA_HOME"])
    javac = shutil.which("javac")
    if javac:
        cands.append(os.path.dirname(os.path.dirname(javac)))
    for base in (r"C:\Program Files\Java", r"C:\Program Files\Eclipse Adoptium", r"C:\Program Files\Microsoft"):
        if not os.path.isdir(base):
            continue
        for name in os.listdir(base):
            cands.append(os.path.join(base, name))
    return cands


def find_jdk():
    """Pick the newest JDK >= 17 (d8/apksigner need Java 11+, we standardize on 17+)."""
    seen = set()
    scored = []
    for cand in jdk_candidates():
        if not cand:
            continue
        key = os.path.normcase(os.path.abspath(cand))
        if key in seen:
            continue
        seen.add(key)
        major = java_major_version(cand)
        if major:
            scored.append((major, cand))
    scored.sort(reverse=True)
    for major, cand in scored:
        if major >= 17:
            return cand
    raise SystemExit("JDK >= 17 not found (d8 requires Java 11+); set TQ_JDK env var")



JDK = find_jdk()
JAVAC = os.path.join(JDK, "bin", "javac.exe")
KEYTOOL = os.path.join(JDK, "bin", "keytool.exe")
JAVA_ENV = dict(os.environ)
JAVA_ENV["JAVA_HOME"] = JDK
JAVA_ENV["PATH"] = os.path.join(JDK, "bin") + os.pathsep + JAVA_ENV.get("PATH", "")


def run(cmd, cwd=None, capture=False):
    printable = " ".join('"%s"' % c if " " in c else c for c in cmd)
    print("+", printable, flush=True)
    kwargs = {"cwd": cwd, "env": JAVA_ENV}
    if capture:
        kwargs.update(capture_output=True, text=True)
    r = subprocess.run(cmd, **kwargs)
    if r.returncode != 0:
        if capture and r.stderr:
            print(r.stderr[-4000:], file=sys.stderr)
        raise SystemExit("command failed (%d): %s" % (r.returncode, printable))
    return r


def bat(bat_path, args, cwd=None):
    return run(["cmd.exe", "/c", bat_path] + args, cwd=cwd)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_manifest_info():
    with open(MANIFEST, "r", encoding="utf-8") as f:
        text = f.read()
    pkg = re.search(r'package="([^"]+)"', text)
    vcode = re.search(r'android:versionCode="(\d+)"', text)
    vname = re.search(r'android:versionName="([^"]+)"', text)
    if not (pkg and vcode and vname):
        raise SystemExit("manifest must declare package/android:versionCode/android:versionName")
    return pkg.group(1), int(vcode.group(1)), vname.group(1)


def bundled_content_version():
    path = os.path.join(WEB_DIR, "version.json")
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            return int(json.load(f).get("contentVersion", 1))
    return 1


def copy_web_to_assets():
    target = os.path.join(ASSETS_DIR, "web")
    if os.path.exists(target):
        shutil.rmtree(target)
    shutil.copytree(WEB_DIR, target, ignore=shutil.ignore_patterns("*.bak", "__pycache__", ".git"))
    print("bundled web ->", os.path.relpath(target, PROJECT_ROOT))


def patch_bundled_version(version):
    patched = []
    pattern = re.compile(r"(BUNDLED_CONTENT_VERSION\s*=\s*)(\d+)")
    for root, _dirs, files in os.walk(JAVA_SRC):
        for name in files:
            if not name.endswith(".java"):
                continue
            path = os.path.join(root, name)
            with open(path, "r", encoding="utf-8") as f:
                text = f.read()
            new_text, count = pattern.subn(lambda m: m.group(1) + str(version), text)
            if count:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new_text)
                patched.append((os.path.relpath(path, PROJECT_ROOT), count))
    if not patched:
        raise SystemExit("BUNDLED_CONTENT_VERSION constant not found in android java sources (expected AppConfig.java)")
    print("patched content version:", version, patched)


def collect_java_sources(gen_dir):
    sources = []
    for root, _dirs, files in os.walk(JAVA_SRC):
        for name in sorted(files):
            if name.endswith(".java"):
                sources.append(os.path.join(root, name))
    for root, _dirs, files in os.walk(gen_dir):
        for name in sorted(files):
            if name.endswith(".java"):
                sources.append(os.path.join(root, name))
    if not sources:
        raise SystemExit("no Java sources found")
    return sources


def build_icons():
    script = os.path.join(PROJECT_ROOT, "tools", "make_icons.py")
    run([sys.executable, script])


def compile_resources():
    res_zip = os.path.join(WORK_DIR, "res.zip")
    run([AAPT2, "compile", "--dir", RES_DIR, "-o", res_zip])


def link_resources(gen_dir, base_apk):
    run(
        [
            AAPT2,
            "link",
            "-o", base_apk,
            "-I", ANDROID_JAR,
            "--manifest", MANIFEST,
            "--java", gen_dir,
            "-A", ASSETS_DIR,
            "-R", os.path.join(WORK_DIR, "res.zip"),
            "--auto-add-overlay",
        ]
    )


def compile_java(gen_dir, classes_dir):
    os.makedirs(classes_dir, exist_ok=True)
    sources = collect_java_sources(gen_dir)
    run(
        [
            JAVAC,
            "-encoding", "UTF-8",
            "-source", "8",
            "-target", "8",
            "-Xlint:-options",
            "-classpath", ANDROID_JAR,
            "-d", classes_dir,
        ]
        + sources
    )


def make_classes_jar(classes_dir):
    jar_path = os.path.join(WORK_DIR, "classes.jar")
    with zipfile.ZipFile(jar_path, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _dirs, files in os.walk(classes_dir):
            for name in sorted(files):
                if not name.endswith(".class"):
                    continue
                full = os.path.join(root, name)
                rel = os.path.relpath(full, classes_dir).replace(os.sep, "/")
                z.write(full, rel)
    return jar_path


def dex_classes(classes_jar):
    dex_dir = os.path.join(WORK_DIR, "dex")
    os.makedirs(dex_dir, exist_ok=True)
    bat(
        D8_BAT,
        [
            "--release",
            "--lib", ANDROID_JAR,
            "--min-api", "26",
            "--output", dex_dir,
            classes_jar,
        ],
    )
    dex = os.path.join(dex_dir, "classes.dex")
    if not os.path.exists(dex):
        raise SystemExit("d8 produced no classes.dex")
    return dex


def assemble_apk(base_apk, dex_path, unsigned_apk):
    with zipfile.ZipFile(base_apk, "r") as src, zipfile.ZipFile(unsigned_apk, "w") as dst:
        for item in src.infolist():
            data = src.read(item.filename)
            new_info = zipfile.ZipInfo(item.filename, date_time=item.date_time)
            new_info.external_attr = item.external_attr
            if item.filename == "resources.arsc":
                new_info.compress_type = zipfile.ZIP_STORED
            else:
                new_info.compress_type = item.compress_type
            dst.writestr(new_info, data)
        dst.write(dex_path, "classes.dex", compress_type=zipfile.ZIP_DEFLATED)


def ensure_debug_keystore():
    if os.path.exists(DEBUG_KEYSTORE):
        return
    os.makedirs(os.path.dirname(DEBUG_KEYSTORE), exist_ok=True)
    run(
        [
            KEYTOOL,
            "-genkeypair",
            "-keystore", DEBUG_KEYSTORE,
            "-storepass", "android",
            "-keypass", "android",
            "-alias", "androiddebugkey",
            "-keyalg", "RSA",
            "-keysize", "2048",
            "-validity", "10000",
            "-dname", "CN=Android Debug,O=Android,C=US",
        ],
        capture=True,
    )


def sign_apk(unsigned_apk, signed_apk):
    ensure_debug_keystore()
    bat(
        APKSIGNER_BAT,
        [
            "sign",
            "--ks", DEBUG_KEYSTORE,
            "--ks-pass", "pass:android",
            "--key-pass", "pass:android",
            "--out", signed_apk,
            unsigned_apk,
        ],
    )
    bat(APKSIGNER_BAT, ["verify", "--print-certs", signed_apk])


def dump_badging(apk):
    r = run([AAPT2, "dump", "badging", apk], capture=True)
    keep = []
    for line in r.stdout.splitlines():
        if line.startswith(("package:", "sdkVersion:", "targetSdkVersion:", "application-label:", "launchable-activity:")):
            keep.append(line)
    print("badging:")
    for line in keep:
        print("  " + line)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version-code", type=int, default=None)
    ap.add_argument("--version-name", default=None)
    ap.add_argument("--skip-icons", action="store_true")
    ap.add_argument("--unsigned-output", default=None, help="optional path to also keep the unsigned apk")
    args = ap.parse_args()

    for p in (AAPT2, ZIPALIGN, ANDROID_JAR):
        if not os.path.exists(p):
            raise SystemExit("missing Android SDK component: " + p)
    if not os.path.exists(MANIFEST):
        raise SystemExit("missing manifest: " + MANIFEST + " (android-dev still working?)")

    missing = [p for p in REQUIRED_WEB if not os.path.exists(os.path.join(WEB_DIR, p))]
    if missing:
        raise SystemExit("web is incomplete, missing: " + ", ".join(missing))

    package, manifest_vcode, manifest_vname = read_manifest_info()
    version_code = args.version_code if args.version_code is not None else manifest_vcode
    version_name = args.version_name if args.version_name is not None else manifest_vname
    content_version = bundled_content_version()

    if os.path.exists(WORK_DIR):
        shutil.rmtree(WORK_DIR)
    os.makedirs(WORK_DIR)
    gen_dir = os.path.join(WORK_DIR, "gen")
    classes_dir = os.path.join(WORK_DIR, "classes")
    os.makedirs(gen_dir)
    os.makedirs(DIST_DIR, exist_ok=True)

    if not args.skip_icons:
        build_icons()
    copy_web_to_assets()
    patch_bundled_version(content_version)
    compile_resources()
    base_apk = os.path.join(WORK_DIR, "base.apk")
    link_resources(gen_dir, base_apk)
    compile_java(gen_dir, classes_dir)
    classes_jar = make_classes_jar(classes_dir)
    dex_path = dex_classes(classes_jar)
    unsigned_apk = os.path.join(WORK_DIR, "unsigned.apk")
    assemble_apk(base_apk, dex_path, unsigned_apk)
    aligned_apk = os.path.join(WORK_DIR, "aligned.apk")
    run([ZIPALIGN, "-f", "4", unsigned_apk, aligned_apk])
    signed_apk = os.path.join(DIST_DIR, "treasure-quest-%s-debug.apk" % version_name)
    if os.path.exists(signed_apk):
        os.remove(signed_apk)
    sign_apk(aligned_apk, signed_apk)
    if args.unsigned_output:
        shutil.copy2(aligned_apk, args.unsigned_output)
    dump_badging(signed_apk)

    size = os.path.getsize(signed_apk)
    digest = sha256_file(signed_apk)
    meta = {
        "file": os.path.relpath(signed_apk, PROJECT_ROOT).replace(os.sep, "/"),
        "sha256": digest,
        "size": size,
        "package": package,
        "shellVersionCode": version_code,
        "shellVersionName": version_name,
        "bundledContentVersion": content_version,
        "signedWith": "debug keystore (.tooling/debug.keystore)",
        "builtAt": __import__("datetime").datetime.now(
            __import__("datetime").timezone(__import__("datetime").timedelta(hours=8))
        ).replace(microsecond=0).isoformat(),
    }
    meta_path = os.path.join(DIST_DIR, "apk-%s.json" % version_name)
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("=" * 60)
    print("APK            :", os.path.relpath(signed_apk, PROJECT_ROOT))
    print("package        :", package, "versionCode", version_code, "versionName", version_name)
    print("bundled content:", content_version)
    print("size           :", size, "bytes")
    print("sha256         :", digest)
    print("metadata       :", os.path.relpath(meta_path, PROJECT_ROOT))
    print("=" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
